import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const OUTPUT = resolve(
  ROOT,
  "src",
  "utils",
  "sinhala",
  "lexicon.generated.js",
);
const SOURCE_URL =
  "https://github.com/kasunw22/sinhala-para-dict/blob/master/V1/En-Si-dict-filtered-V1.tsv";
const FALSE_POSITIVE_RATE = 0.00001;
const LATIN_LEXEME_RE = /^\p{Script=Latin}+(?:['’.-]\p{Script=Latin}+)*$/u;
const SINHALA_LEXEME_RE = /^[\u0d80-\u0dff\u200c\u200d]+$/u;

function hashLexeme(value, seed) {
  let hash = seed >>> 0;
  for (let index = 0; index < value.length; index += 1) {
    hash ^= value.charCodeAt(index);
    hash = Math.imul(hash, 0x01000193);
  }
  hash ^= hash >>> 16;
  hash = Math.imul(hash, 0x85ebca6b);
  hash ^= hash >>> 13;
  hash = Math.imul(hash, 0xc2b2ae35);
  return (hash ^ (hash >>> 16)) >>> 0;
}

function isPrime(value) {
  if (value < 2 || value % 2 === 0) return value === 2;
  for (let divisor = 3; divisor * divisor <= value; divisor += 2) {
    if (value % divisor === 0) return false;
  }
  return true;
}

function nextPrime(value) {
  let candidate = Math.max(3, Math.ceil(value)) | 1;
  while (!isPrime(candidate)) candidate += 2;
  return candidate;
}

function createBloomFilter(words) {
  const bitCount = nextPrime(
    (-words.size * Math.log(FALSE_POSITIVE_RATE)) / Math.log(2) ** 2,
  );
  const hashCount = Math.max(
    1,
    Math.round((bitCount / words.size) * Math.log(2)),
  );
  const bits = new Uint8Array(Math.ceil(bitCount / 8));

  for (const word of words) {
    const firstHash = hashLexeme(word, 0x811c9dc5);
    const secondHash = hashLexeme(word, 0x9e3779b9) | 1;
    for (let index = 0; index < hashCount; index += 1) {
      const bit =
        ((firstHash + Math.imul(index, secondHash)) >>> 0) % bitCount;
      bits[bit >>> 3] |= 1 << (bit & 7);
    }
  }

  return {
    bitCount,
    hashCount,
    wordCount: words.size,
    data: Buffer.from(bits).toString("base64"),
  };
}

function formatBase64(value) {
  return value.match(/.{1,100}/g).map((line) => `    "${line}",`).join("\n");
}

const sourcePath = process.argv[2];
if (!sourcePath) {
  throw new Error(
    "Usage: node scripts/generate-sinhala-conversion-lexicon.mjs <En-Si-dict-filtered-V1.tsv>",
  );
}

const source = await readFile(resolve(sourcePath));
const englishWords = new Set();
const sinhalaWords = new Set();

for (const line of source.toString("utf8").split(/\r?\n/u)) {
  const separator = line.indexOf("\t");
  if (separator < 0) continue;

  const english = line
    .slice(0, separator)
    .normalize("NFKC")
    .toLocaleLowerCase("en");
  const sinhala = line.slice(separator + 1).trim().normalize("NFC");
  if (LATIN_LEXEME_RE.test(english)) englishWords.add(english);
  if (SINHALA_LEXEME_RE.test(sinhala)) sinhalaWords.add(sinhala);
}

const english = createBloomFilter(englishWords);
const sinhala = createBloomFilter(sinhalaWords);
const sha256 = createHash("sha256").update(source).digest("hex");
const generated = `// AUTO GENERATED by scripts/generate-sinhala-conversion-lexicon.mjs
// Source: ${SOURCE_URL}
// Source SHA-256: ${sha256}
// Bloom-filter target false-positive rate: ${FALSE_POSITIVE_RATE}

export const SINHALA_CONVERSION_LEXICON = {
  english: {
    bitCount: ${english.bitCount},
    hashCount: ${english.hashCount},
    wordCount: ${english.wordCount},
    chunks: [
${formatBase64(english.data)}
    ],
  },
  sinhala: {
    bitCount: ${sinhala.bitCount},
    hashCount: ${sinhala.hashCount},
    wordCount: ${sinhala.wordCount},
    chunks: [
${formatBase64(sinhala.data)}
    ],
  },
};
`;

await writeFile(OUTPUT, generated, "utf8");
console.log(
  `Generated ${english.wordCount} English and ${sinhala.wordCount} Sinhala lexemes at ${OUTPUT}`,
);
