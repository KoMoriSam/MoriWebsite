import assert from "node:assert/strict";
import { computed, createSSRApp, h } from "vue";
import { renderToString } from "@vue/server-renderer";
import { DEFAULT_AVATAR } from "../src/constants/markdown.js";
import { getMarkdownAvatar, loadAvatarManifest, registerAvatarManifest } from "../src/utils/markdown/avatar-manifests.js";
import { registerImageManifest } from "../src/utils/images/responsive-images.js";
import { provideMarkdownAvatars, useMarkdownAvatars } from "../src/composables/markdown/useMarkdownAvatars.js";

const blog = "https://pages.example/blog";
const novel = "https://pages.example/novel";
const manifest = { version: 1, avatars: { Mori: "avatar/ayanami.webp" } };
registerAvatarManifest(blog, manifest);
registerAvatarManifest(novel, manifest);
assert.equal(getMarkdownAvatar(blog, " Mori "), `${blog}/images/avatar/ayanami.webp`);
assert.equal(getMarkdownAvatar(novel, "Mori"), `${novel}/images/avatar/ayanami.webp`);
assert.equal(getMarkdownAvatar(blog, "Unknown"), DEFAULT_AVATAR);
assert.equal(getMarkdownAvatar(blog, "toString"), DEFAULT_AVATAR);
assert.equal(getMarkdownAvatar("", "Mori"), DEFAULT_AVATAR);
registerAvatarManifest("/mock/novel", manifest);
assert.equal(getMarkdownAvatar("/mock/novel", "Mori"), "/mock/novel/images/avatar/ayanami.webp");
const reactiveAvatar = computed(() => getMarkdownAvatar(novel, "Mori"));
assert.match(reactiveAvatar.value, /ayanami/u);
registerAvatarManifest(novel, { version: 1, avatars: { Mori: "avatar/updated.webp" } });
assert.equal(reactiveAvatar.value, `${novel}/images/avatar/updated.webp`);
registerAvatarManifest(novel, manifest);
registerAvatarManifest(blog, { version: 1, avatars: { Mori: "avatar/ayanami.webp", Unsafe: "../outside.webp", External: "https://evil.example/avatar.webp", Script: "javascript:alert(1)", Encoded: "%2e%2e/outside.webp", Query: "avatar/x.webp?token=x" } });
for (const name of ["Unsafe", "External", "Script", "Encoded", "Query"]) assert.equal(getMarkdownAvatar(blog, name), DEFAULT_AVATAR);
registerImageManifest({ version: 1, images: { "avatar/ayanami.webp": { width: 512, height: 512, variants: [{ src: "_optimized/abc-64.webp", width: 64 }, { src: "_optimized/abc-128.webp", width: 128 }] } } }, `${blog}/images/`);

const originalFetch = globalThis.fetch;
let fetches = 0;
globalThis.fetch = async () => { fetches += 1; return { ok: true, json: async () => manifest }; };
try {
  let attrs;
  const Child = { setup() { const { avatarAttrs } = useMarkdownAvatars(); return () => { attrs = avatarAttrs("Mori"); return h("img", attrs); }; } };
  const app = createSSRApp({ setup() { provideMarkdownAvatars(blog); return () => h(Child); } });
  const html = await renderToString(app);
  await loadAvatarManifest(blog);
  assert.match(html, /srcset=/u);
  assert.match(html, /sizes="40px"/u);
  const attributes = { ...attrs };
  let stops = 0;
  const image = { getAttribute: (name) => attributes[name], removeAttribute: (name) => { delete attributes[name]; }, set src(value) { attributes.src = value; } };
  const event = { currentTarget: image, stopImmediatePropagation: () => { stops += 1; } };
  attrs.onError(event);
  assert.equal(attributes.src, `${blog}/images/avatar/ayanami.webp`);
  assert.equal(stops, 1);
  attrs.onError(event);
  assert.equal(attributes.src, DEFAULT_AVATAR);
  attrs.onError(event);
  assert.equal(attributes.src, DEFAULT_AVATAR);
  assert.equal(attributes["data-original-src"], undefined);
  await Promise.all([loadAvatarManifest(novel), loadAvatarManifest(novel)]);
  assert.equal(fetches, 2);
  globalThis.fetch = async () => { fetches += 1; return { ok: false, status: 404 }; };
  await Promise.all([loadAvatarManifest("https://missing.example"), loadAvatarManifest("https://missing.example")]);
  assert.equal(fetches, 3);
  await loadAvatarManifest("https://missing.example");
  assert.equal(fetches, 4);
  const defaultHtml = await renderToString(createSSRApp(Child));
  assert.ok(defaultHtml.includes(DEFAULT_AVATAR));
  console.log("Markdown avatar checks passed: repository isolation, reactive maps, provider inheritance, srcset, fallback, safe URLs, request deduplication and retries.");
} finally { globalThis.fetch = originalFetch; }
